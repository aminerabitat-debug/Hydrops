def _generate_prv_rows(seed: list[tuple], start_id: int) -> list[tuple]:
    """PRV (verre-resine) n'a pas encore sa propre serie de prix — consigne utilisateur : "recopie
    en un premier temps le catalogue de l'acier en partant du DN300" (memes DI/PMS/prix que
    l'Acier correspondant, juste retiquete "PRV"), a affiner plus tard avec de vraies donnees."""
    rows: list[tuple] = []
    next_id = start_id
    for row in seed:
        _id, dn, di, material, pressure_class, pms, prix_ftp, prix_fourniture, prix_aps = row
        if material == "Acier" and dn >= 300:
            rows.append((next_id, dn, di, "PRV", pressure_class, pms, prix_ftp, prix_fourniture, prix_aps))
            next_id += 1
    return rows


